function line(g: Ctx, str: string, x: number, y: number, s: number, top: string, bot: string) {
  const pass = (fn: (px: number, py: number, r: number) => void) => {
    let cx = x
    for (const ch of str) {
      if (ch !== ' ') G[ch].forEach((row, r) => [...row].forEach((on, c) => on === '1' && fn(cx + c * s, y + r * s, r)))
      cx += (ch === ' ' ? 4 : 6) * s
    }
  }
  g.fillStyle = '#0b1716'
  pass((px, py) => g.fillRect(px - 1, py - 1, s + 2, s + 3))
  pass((px, py, r) => {
    g.fillStyle = r < 3 ? top : bot
    g.fillRect(px, py, s, s)
  })
}

